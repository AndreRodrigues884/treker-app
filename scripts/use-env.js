// Chooses which Supabase the app talks to: copies .env.<environment> to .env.local, which Expo
// reads before any other .env file. Run by `npm start` (development: the local Supabase) and
// `npm run start:prod` (production: the online project), so the dev server stays in development
// mode (fast refresh, logs) either way. See docs/auth.md.
//
//   node scripts/use-env.js development|production
const fs = require('fs');
const path = require('path');

const environments = ['development', 'production'];
const environment = process.argv[2];

if (!environments.includes(environment)) {
  console.error(`Usage: node scripts/use-env.js ${environments.join('|')}`);
  process.exit(1);
}

const root = path.join(__dirname, '..');
const source = path.join(root, `.env.${environment}`);
const target = path.join(root, '.env.local');

if (!fs.existsSync(source)) {
  console.error(
    `Missing .env.${environment}. Copy .env.${environment}.example to .env.${environment} and fill it in.`,
  );
  process.exit(1);
}

const header =
  `# Generated by scripts/use-env.js from .env.${environment}. Do not edit: change ` +
  `.env.${environment} and start again.\n`;
fs.writeFileSync(target, header + fs.readFileSync(source, 'utf8'));

const url = /^EXPO_PUBLIC_SUPABASE_URL=(.*)$/m.exec(fs.readFileSync(source, 'utf8'))?.[1] ?? '';
console.log(`Supabase: ${environment} (${url.trim() || 'no URL set'})`);
